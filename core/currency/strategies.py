CHAPTERS = {item[1]: item[3] for item in STRATEGIES}


def min_plane_of(name):
    """某条策略最早能在第几面刷到；不认识的名字按第 1 面算。"""
    return MIN_PLANE.get(name, 1)


def exit_plane_for(targets, collected):
    """按「未收集的目标策略」推算需要打到第几面。

    取所有未收集目标里最早位面的最大值；目标全收完就退回第 1 面（最低面），
    避免为了不可能再出现的东西多打两面。
    """
    pending = [name for name in targets if name not in collected]
    if not pending:
        return 1
    return max(min_plane_of(name) for name in pending)


# 「佩佩在场」相关策略：拿到其中任意一条，场上就有佩佩了（孪生姵姵的前置条件）。
# 名字来自解包名单；「孪生姵姵」本身是目标，不算在内。
PEPE_FIELD_STRATEGIES = ("溜佩佩", "溜佩佩+", "佩佩客串", "佩佩驾到")
# 依赖「佩佩在场」才能出现的策略（位面 2~3）
PEPE_DEPENDENT_STRATEGIES = ("孪生姵姵",)


# 「佩佩被带走」的关键词：这条策略会让佩佩离开，对刷孪生姵姵是绝对负面。
# 名字不在 298 条名单里（实测 OCR 到的是说明文字「阿兰接走佩佩们并留下所有装备」），
# 所以按关键词兜，命中就不再走佩佩特化。
PEPE_LEAVE_KEYWORDS = ("阿兰", "接走佩佩")


def pepe_left(*texts):
    """本屏是否出现了会让佩佩离开的策略。"""
    for text in texts:
        normalized = normalize_name(text or "")
        if any(normalize_name(word) in normalized for word in PEPE_LEAVE_KEYWORDS):
            return True
    return False


# 「自动取消勾选」不动的佩佩策略：这些都是刷孪生姵姵要一直盯着的。
# 注意「佩佩客串」不在里面——它是负面，照常按常规逻辑清掉。
PEPE_KEEP_CHECKED = ("孪生姵姵", "佩佩驾到", "溜佩佩", "溜佩佩+")


# 「投资环境」里也会直接把佩佩送到场上：三星佩佩 / 粗星佩佩。
# 拿到这类环境等同于拿到了佩佩，孪生姵姵的前置条件同样满足。
PEPE_ENVIRONMENTS = ("三星佩佩", "粗星佩佩")


def pepe_env_on_field(texts):
    """本屏出现的环境里有没有直接给佩佩的。"""
    for text in texts or ():
        if not text:
            continue
        normalized = normalize_name(text)
        if any(normalize_name(name) in normalized for name in PEPE_ENVIRONMENTS):
            return True
    return False


def pepe_goal_reached(name):
    """这条是不是「最终目标」策略（孪生姵姵）——拿到就意味着这个系列可以收工了。

    名字里那个「姵」是生僻字，OCR 大概率读成「佩」，所以比较前先把 姵 统一成 佩。
    """
    def canon(text):
        return normalize_name(text or "").replace("姵", "佩")

    target = canon(name)
    return any(target == canon(item) for item in PEPE_DEPENDENT_STRATEGIES)


def pepe_keep_checked(name):
    """这条命中的目标策略要不要保留勾选（不清掉）。"""
    return normalize_name(name) in {normalize_name(item) for item in PEPE_KEEP_CHECKED}


def pepe_on_field(name):
    """这条策略拿到的同时，场上是否已经有佩佩。"""
    return normalize_name(name) in {normalize_name(item) for item in PEPE_FIELD_STRATEGIES}


_SEPARATORS = re.compile(r"[•·・‧\s\-—_]+")


def normalize_name(text):
    """去掉间隔点、空白与连接符，便于比较（OCR 常把「•」吃掉）。"""
    return _SEPARATORS.sub("", text or "")


def _allowed_edits(length):
    if length <= 2:
        return 0
    return 1 if length <= 6 else 2


def match_name(text):
    """把 OCR 文本对齐到 298 条名单里最像的一个；都不够像就返回 None。

    容错额度按长度给：≤2 字必须完全一致（避免「头彩/尾彩」这类短名字互相糊），
    3~6 字允许 1 个字错，更长允许 2 个。
    """
    text = normalize_name(text)
    if not text:
        return None
    best, best_score = None, 0.0
    for name in STRATEGY_NAMES:
        candidate = normalize_name(name)
        if candidate == text:
            return name
        score = SequenceMatcher(None, text, candidate).ratio()
        if score > best_score:
            best, best_score = name, score
    if best is None:
        return None
    longest = max(len(text), len(normalize_name(best)))
    if best_score >= 1 - _allowed_edits(longest) / longest:
        return best
    return None
